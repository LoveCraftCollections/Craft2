/**
 * Image pipeline for Mana Pelli.
 *
 * Produces the art-directed hero set (portrait for phones, landscape for
 * tablets/desktop) plus the Open Graph card. Run with:
 *
 *   node scripts/optimize-images.mjs
 *
 * Sources live in public/images as *_source.png (not committed). The script is
 * idempotent: it only rewrites files from a source that exists.
 */
import { mkdir, writeFile, access } from "node:fs/promises";
import { join } from "node:path";
import sharp from "sharp";

const ROOT = new URL("..", import.meta.url).pathname;
const IMAGES = join(ROOT, "public/images");
// Source art is kept outside public/ so the multi-megabyte originals are never
// served to visitors (and never land in a WhatsApp link preview request).
const SOURCES = join(ROOT, "assets/source");
const HERO_OUT = join(IMAGES, "hero");

const exists = async (path) => {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
};

const variant = async (source, outDir, name, width, format, extra = {}) => {
  const pipeline = sharp(source).resize({ width, withoutEnlargement: true, fit: "inside" });
  const buffer =
    format === "avif"
      ? await pipeline.avif({ quality: 52, effort: 6, chromaSubsampling: "4:2:0" }).toBuffer()
      : await pipeline.webp({ quality: 76, effort: 5 }).toBuffer();
  const file = join(outDir, `${name}.${format}`);
  await writeFile(file, buffer);
  console.log(`${file.replace(ROOT, "")}  ${(buffer.length / 1024).toFixed(1)}kB  ${width}w${extra.note ?? ""}`);
  return buffer;
};

const lqip = async (source, width = 26) => {
  const buffer = await sharp(source).resize({ width }).webp({ quality: 42 }).toBuffer();
  return `data:image/webp;base64,${buffer.toString("base64")}`;
};

const buildHero = async () => {
  const portraitSource = join(SOURCES, "hero-mobile-source.png");
  const landscapeSource = join(IMAGES, "konaseema-hero.webp");

  if (await exists(portraitSource)) {
    await mkdir(HERO_OUT, { recursive: true });
    for (const width of [440, 660, 880]) {
      for (const format of ["avif", "webp"]) {
        await variant(portraitSource, HERO_OUT, `hero-portrait-${width}`, width, format);
      }
    }
    const portraitLqip = await lqip(portraitSource);
    console.log("portrait lqip", portraitLqip.length, "chars");
  }

  if (await exists(landscapeSource)) {
    await mkdir(HERO_OUT, { recursive: true });
    for (const width of [960, 1376]) {
      for (const format of ["avif", "webp"]) {
        await variant(landscapeSource, HERO_OUT, `hero-landscape-${width}`, width, format);
      }
    }
    const landscapeLqip = await lqip(landscapeSource);
    console.log("landscape lqip", landscapeLqip.length, "chars");

    await writeFile(
      join(ROOT, "src/data/hero-lqip.ts"),
      `// Generated by scripts/optimize-images.mjs — tiny blurred placeholders that\n// paint instantly while the art-directed hero photograph decodes.\n\nexport const heroPortraitLqip = "${portraitLqip}";\n\nexport const heroLandscapeLqip = "${landscapeLqip}";\n`,
    );
    console.log("src/data/hero-lqip.ts updated");

    // WhatsApp / social link preview card.
    const og = await sharp(landscapeSource)
      .resize({ width: 1200, height: 630, fit: "cover", position: "attention" })
      .jpeg({ quality: 82, mozjpeg: true })
      .toBuffer();
    await writeFile(join(IMAGES, "og-mana-pelli.jpg"), og);
    console.log(`og-mana-pelli.jpg  ${(og.length / 1024).toFixed(1)}kB`);

  }
};

const buildSupporting = async () => {
  const jobs = [
    { source: "vindhu-source.png", name: "vindhu-bhojanam" },
    { source: "bobbatlu-source.png", name: "bobbatlu" },
    { source: "payasam-source.png", name: "paramannam" },
    { source: "pasupu-source.png", name: "pasupu-ceremony" },
  ];

  for (const job of jobs) {
    const source = join(SOURCES, job.source);
    if (!(await exists(source))) continue;
    const buffer = await sharp(source).resize({ width: 1400, withoutEnlargement: true }).webp({ quality: 78, effort: 6 }).toBuffer();
    const file = join(IMAGES, `${job.name}.webp`);
    await writeFile(file, buffer);
    console.log(`${file.replace(ROOT, "")}  ${(buffer.length / 1024).toFixed(1)}kB`);
  }
};

await buildHero();
await buildSupporting();
